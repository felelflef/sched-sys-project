-- ─────────────────────────────────────────────────────────────
-- Scheduling System — PostgreSQL schema (Aiven PostgreSQL, database 'defaultdb')
--
-- The app runs this file itself the first time it connects (and again after SCHEMA_VERSION in
-- config/db.php changes), and tools/setup_pg.php runs it when setting up a new database. Every
-- statement is safe to run again: nothing is replaced or deleted.
--
-- Starting data: only the seven subject areas and one FCC certificate for each, added once.
-- Rooms, teachers, subjects, school years, terms, sections and schedules are entered in the app.
-- ─────────────────────────────────────────────────────────────

-- Emails compare without regard to capital letters, as they did on MySQL
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS classrooms (
    room_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name_number VARCHAR(50) NOT NULL,
    room_type VARCHAR(10) NOT NULL CHECK (room_type IN ('Lecture', 'Lab', 'CompLab', 'Kitchen', 'Bar', 'Special')),
    capacity INT NOT NULL,
    floor_level INT NOT NULL,
    current_status VARCHAR(10) DEFAULT 'Vacant' CHECK (current_status IN ('Vacant', 'Occupied', 'Reserved'))
);

CREATE TABLE IF NOT EXISTS users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email CITEXT NOT NULL UNIQUE CHECK (char_length(email) <= 100),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'program-head', 'faculty')),
    subject_role VARCHAR(50) DEFAULT 'IT',
    active_session_token VARCHAR(255) DEFAULT NULL,
    employment_status VARCHAR(20) NOT NULL DEFAULT 'Full-time',
    available_days VARCHAR(30) NOT NULL DEFAULT '',
    available_shifts VARCHAR(30) NOT NULL DEFAULT '',
    max_load INT NOT NULL DEFAULT 30,
    min_load INT DEFAULT NULL,
    teaching_level VARCHAR(10) NOT NULL DEFAULT 'tertiary',
    seasoned SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS school_years (
    year_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year_code VARCHAR(50) NOT NULL,
    is_active SMALLINT DEFAULT 0,
    created_at TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uniq_year_code UNIQUE (year_code)
);

CREATE TABLE IF NOT EXISTS school_terms (
    schedule_version INT NOT NULL DEFAULT 0,
    term_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year_id INT NOT NULL REFERENCES school_years(year_id) ON DELETE CASCADE,
    term_name VARCHAR(30) NOT NULL,
    level VARCHAR(10) NOT NULL DEFAULT 'tertiary',
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(10) DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'closed')),
    is_active SMALLINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS term_subjects (
    subject_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id INT NOT NULL REFERENCES school_terms(term_id) ON DELETE CASCADE,
    subject_code VARCHAR(20) NOT NULL,
    subject_name VARCHAR(100) NOT NULL,
    units INT NOT NULL DEFAULT 3,
    lab_units SMALLINT DEFAULT NULL,
    lecture_hours DECIMAL(4,1) NOT NULL DEFAULT 3.0,
    lab_hours DECIMAL(4,1) NOT NULL DEFAULT 0.0,
    subject_type VARCHAR(10) DEFAULT 'lecture' CHECK (subject_type IN ('lecture', 'lab', 'pe', 'special')),
    program VARCHAR(20) NOT NULL DEFAULT 'BSIT',
    year_level INT NOT NULL DEFAULT 1,
    curriculum VARCHAR(50) DEFAULT '2024 Revised',
    is_included SMALLINT DEFAULT 1
);

CREATE TABLE IF NOT EXISTS academic_sections (
    section_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id INT NOT NULL REFERENCES school_terms(term_id) ON DELETE CASCADE,
    section_code VARCHAR(20) NOT NULL,
    section_name VARCHAR(50) NOT NULL,
    program VARCHAR(20) NOT NULL,
    year_level INT NOT NULL,
    student_count INT NOT NULL DEFAULT 35,
    adviser VARCHAR(100) DEFAULT NULL,
    shift VARCHAR(20) DEFAULT 'AM',
    home_room VARCHAR(50) DEFAULT NULL,
    subject_teachers TEXT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS schedules (
    schedule_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id INT NULL,
    room_id INT NOT NULL REFERENCES classrooms(room_id) ON DELETE CASCADE,
    faculty_id INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    subject_code VARCHAR(20) NOT NULL,
    subject_category VARCHAR(50) DEFAULT 'IT',
    section_name VARCHAR(20) NOT NULL,
    day_of_week VARCHAR(3) NOT NULL CHECK (day_of_week IN ('Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat')),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    ai_generated SMALLINT NOT NULL DEFAULT 0,
    is_locked SMALLINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_schedules_term_day ON schedules (term_id, day_of_week);

CREATE TABLE IF NOT EXISTS schedule_snapshots (
    term_id INT PRIMARY KEY,
    saved_at TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
    schedule_json TEXT NOT NULL
);

-- Sign-ins, kept in the database so they survive restarts and deploys
CREATE TABLE IF NOT EXISTS app_sessions (
    session_id VARCHAR(128) PRIMARY KEY,
    data TEXT NOT NULL,
    updated_at INT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_updated ON app_sessions (updated_at);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key VARCHAR(50) PRIMARY KEY,
    setting_value VARCHAR(255) NOT NULL
);

-- Failed sign-in counters; keys are hashed so no email or IP is stored
CREATE TABLE IF NOT EXISTS login_attempts (
    attempt_key CHAR(64) PRIMARY KEY,
    attempts INT NOT NULL,
    window_start INT NOT NULL
);

CREATE TABLE IF NOT EXISTS departments (
    department_name VARCHAR(100) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS subject_catalog (
    subject_code VARCHAR(20) PRIMARY KEY,
    subject_title VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    it_only SMALLINT DEFAULT 0,
    units INT NOT NULL DEFAULT 3,
    level VARCHAR(10) NOT NULL DEFAULT 'both',
    catalog_id INT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

-- Change history: who saved what, and when (repeated in includes/activity.php for a database that lacks it)
CREATE TABLE IF NOT EXISTS activity_log (
    log_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    user_email VARCHAR(100) NOT NULL,
    user_name VARCHAR(101) NOT NULL,
    user_role VARCHAR(20) NOT NULL,
    category VARCHAR(20) NOT NULL,
    summary VARCHAR(500) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_activity_time ON activity_log (created_at);

-- Reusable subject lists (for example a 1st or 2nd semester), loaded into a term in Step 3
CREATE TABLE IF NOT EXISTS subject_sets (
    set_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_name VARCHAR(60) NOT NULL UNIQUE,
    items_json TEXT NOT NULL
);

-- FCC certificates: each covers one or more subject areas (departments)
CREATE TABLE IF NOT EXISTS fcc_certificates (
    cert_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cert_name VARCHAR(60) NOT NULL UNIQUE,
    areas_json TEXT NOT NULL
);

-- The subjects each teacher is allowed to teach
CREATE TABLE IF NOT EXISTS faculty_qualifications (
    user_id INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    subject_code VARCHAR(20) NOT NULL,
    PRIMARY KEY (user_id, subject_code)
);

-- The FCC certificates each teacher holds
CREATE TABLE IF NOT EXISTS faculty_certificates (
    user_id INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    cert_id INT NOT NULL REFERENCES fcc_certificates(cert_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, cert_id)
);

